#!/usr/bin/env python3
"""Normalize G-code for Filuna foundation baseline compares.

STRICT allowlist: only drop/stabilize known non-functional metadata lines.
Never rewrite motion/extrusion/temperature/layer command semantics.
Inline "; comment" after a command is preserved as part of the command line
(only whole-line metadata comments matching the allowlist are removed).
Empty/corrupt inputs fail closed.
"""
from __future__ import annotations

import argparse
import hashlib
import re
import sys
from pathlib import Path

# Whole-line metadata allowlist (must match entire line after rstrip newline).
# Anything else that looks like a command or non-allowlisted comment is KEPT.
META_LINE_ALLOWLIST = [
    re.compile(r"^;\s*generated by .* on .*$", re.I),
    re.compile(r"^;\s*filename\s*=.*$", re.I),
    re.compile(r"^;\s*header_uuid\s*=.*$", re.I),
    re.compile(r"^;\s*USER_AGENT\s*=.*$", re.I),
    re.compile(r"^;\s*thumbnail begin.*$", re.I),
    re.compile(r"^;\s*thumbnail end.*$", re.I),
    re.compile(r"^;\s*thumbnail_.*$", re.I),  # thumbnail payload lines between begin/end may vary
]

# Absolute paths only inside pure comment lines (line starts with ;).
ABS_PATH_IN_COMMENT = re.compile(
    r"(;.*?=)\s*(?:[A-Za-z]:\\|/)[^\n]*"
)

# Thumbnail base64-ish payload lines between begin/end (optional strip while in block)
THUMB_BEGIN = re.compile(r"^;\s*thumbnail begin", re.I)
THUMB_END = re.compile(r"^;\s*thumbnail end", re.I)


def is_allowlisted_meta_line(line: str) -> bool:
    s = line.rstrip("\r\n")
    if not s.lstrip().startswith(";"):
        return False
    for rx in META_LINE_ALLOWLIST:
        if rx.match(s):
            return True
    return False


def stabilize_comment_paths(line: str) -> str:
    """Only rewrite absolute paths on pure comment lines."""
    if not line.lstrip().startswith(";"):
        return line
    return ABS_PATH_IN_COMMENT.sub(r"\1 <PATH>", line)


def normalize_gcode_text(text: str) -> str:
    if text is None:
        raise ValueError("empty gcode text")
    # Reject obvious binary/corrupt (NUL)
    if "\x00" in text:
        raise ValueError("corrupt gcode: contains NUL")
    out: list[str] = []
    in_thumb = False
    for line in text.splitlines(keepends=True):
        raw = line.rstrip("\r\n")
        if THUMB_BEGIN.match(raw):
            in_thumb = True
            continue  # drop begin
        if in_thumb:
            if THUMB_END.match(raw):
                in_thumb = False
            continue  # drop thumb payload + end
        if is_allowlisted_meta_line(line):
            continue
        line = stabilize_comment_paths(line)
        if line.endswith("\r\n"):
            line = line[:-2] + "\n"
        elif line.endswith("\r"):
            line = line[:-1] + "\n"
        out.append(line)
    body = "".join(out)
    if body and not body.endswith("\n"):
        body += "\n"
    return body


def normalize_file(path: Path) -> str:
    if not path.is_file():
        raise FileNotFoundError(f"missing gcode: {path}")
    if path.stat().st_size == 0:
        raise ValueError(f"empty gcode file: {path}")
    data = path.read_bytes()
    if b"\x00" in data:
        raise ValueError(f"corrupt gcode (NUL): {path}")
    # Prefer utf-8; reject if mostly non-text
    text = data.decode("utf-8", errors="replace")
    return normalize_gcode_text(text)


def sha256_text(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("gcode", type=Path)
    p.add_argument("--out", type=Path, default=None)
    p.add_argument("--print-sha256", action="store_true")
    args = p.parse_args(argv)
    try:
        norm = normalize_file(args.gcode)
    except (OSError, ValueError) as exc:
        print(f"FAIL: {exc}", file=sys.stderr)
        return 2
    if args.out:
        args.out.write_text(norm, encoding="utf-8")
    if args.print_sha256 or not args.out:
        print(sha256_text(norm))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
