#!/usr/bin/env python3
"""Normalize G-code for Filuna foundation baseline compares.

Allowed: strip/stabilize non-functional metadata only.
Forbidden: changing motion/extrusion/temperature trajectory semantics.
"""
from __future__ import annotations

import argparse
import hashlib
import re
import sys
from pathlib import Path

# Comment/header patterns considered non-functional metadata (SPEC §5).
META_LINE_RES = [
    re.compile(r"^;\s*generated by .* on .*$", re.I),
    re.compile(r"^;\s*filename\s*=.*$", re.I),
    re.compile(r"^;\s*header_uuid\s*=.*$", re.I),
    re.compile(r"^;\s*USER_AGENT\s*=.*$", re.I),
    re.compile(r"^;\s*thumbnail begin.*$", re.I),
    re.compile(r"^;\s*thumbnail end.*$", re.I),
]

# Absolute path-ish assignments inside comments
ABS_PATH_IN_COMMENT = re.compile(
    r"(;.*?=)\s*(?:[A-Za-z]:\\|/)[^\n]*"
)


def is_meta_line(line: str) -> bool:
    s = line.rstrip("\n")
    for rx in META_LINE_RES:
        if rx.match(s):
            return True
    return False


def stabilize_comment_paths(line: str) -> str:
    if not line.lstrip().startswith(";"):
        return line
    return ABS_PATH_IN_COMMENT.sub(r"\1 <PATH>", line)


def normalize_gcode_text(text: str) -> str:
    out: list[str] = []
    for line in text.splitlines(keepends=True):
        if is_meta_line(line):
            continue
        line = stabilize_comment_paths(line)
        # Normalize EOL to \n without altering command content
        if line.endswith("\r\n"):
            line = line[:-2] + "\n"
        elif line.endswith("\r"):
            line = line[:-1] + "\n"
        out.append(line)
    body = "".join(out)
    if body and not body.endswith("\n"):
        body += "\n"
    return body


def normalize_file(path: Path) -> str:
    return normalize_gcode_text(path.read_text(encoding="utf-8", errors="replace"))


def sha256_text(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("gcode", type=Path)
    p.add_argument("--out", type=Path, default=None)
    p.add_argument("--print-sha256", action="store_true")
    args = p.parse_args(argv)
    if not args.gcode.is_file():
        print(f"FAIL: missing file {args.gcode}", file=sys.stderr)
        return 2
    norm = normalize_file(args.gcode)
    if args.out:
        args.out.write_text(norm, encoding="utf-8")
    if args.print_sha256 or not args.out:
        print(sha256_text(norm))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
