#!/usr/bin/env python3
"""Strict OEM G-code E8 comparison: ignore ONLY generator date/time and
program name/version metadata within HEADER_BLOCK. Never ignore print time,
geometry, filament, preset or executable G-code differences.

No claim that a pre-existing Orca binary constitutes the new OEM engine.
"""
import argparse,hashlib,itertools,json,re
from pathlib import Path

GENERATOR_LINE=re.compile(r"^;\s*(?:generated by\s+\S+|BambuStudio\s+\S+|OrcaSlicer\s+\S+|FilunaSlicer\s+\S+)(?:\s+.*)?$",re.I)
GENERATION_TIMESTAMP=re.compile(r"^;\s*(?:generated at|creation date|creation time|file generated at)\s*[:=]\s*.+$",re.I)

def records(path):
    section="OUTSIDE"
    with path.open("rb") as fh:
        for number,raw in enumerate(fh,1):
            line=raw.decode("utf-8","replace").rstrip("\r\n")
            if line=="; HEADER_BLOCK_START":section="HEADER"
            elif line=="; CONFIG_BLOCK_START":section="CONFIG"
            elif line=="; EXECUTABLE_BLOCK_START":section="EXEC"
            suppressed=section=="HEADER" and (GENERATOR_LINE.fullmatch(line) or GENERATION_TIMESTAMP.fullmatch(line))
            if not suppressed:yield number,section,raw
            if line in ("; HEADER_BLOCK_END","; CONFIG_BLOCK_END","; EXECUTABLE_BLOCK_END"):section="OUTSIDE"

def fingerprint(path):
    sha=hashlib.sha256()
    for _,_,raw in records(path):sha.update(raw)
    return sha.hexdigest()

def first_difference(lhs,rhs,section=None):
    def filtered(path):
        for n,s,line in records(path):
            if section is None or s==section:
                yield (n,s,line)
    count=0
    for a,b in itertools.zip_longest(filtered(lhs),filtered(rhs)):
        if a is None or b is None or a[2]!=b[2]:
            return {"matched_lines_before":count,"official_line":a[0] if a else None,
                    "official":a[2].decode("utf-8","replace").rstrip("\r\n")[:500] if a else None,
                    "filuna_line":b[0] if b else None,
                    "filuna":b[2].decode("utf-8","replace").rstrip("\r\n")[:500] if b else None,
                    "section":section or "ALL"}
        count+=1
    return None

def main():
    ap=argparse.ArgumentParser()
    ap.add_argument("--official",type=Path,required=True)
    ap.add_argument("--filuna",type=Path,required=True)
    ap.add_argument("--out",type=Path,required=True)
    ap.add_argument("--candidate-is-integrated-oem",action="store_true")
    ap.add_argument("--gate",choices=["B","C","NEGATIVE"],default="NEGATIVE")
    a=ap.parse_args()
    raw_off=hashlib.sha256(a.official.read_bytes()).hexdigest()
    raw_fil=hashlib.sha256(a.filuna.read_bytes()).hexdigest()
    norm_off=fingerprint(a.official);norm_fil=fingerprint(a.filuna)
    result={"criterion":"exact normalized SHA256 after generator identity/date removal in HEADER only",
            "official_file":str(a.official),"filuna_file":str(a.filuna),
            "candidate_integrated_oem_engine":a.candidate_is_integrated_oem,
            "gate":a.gate,
            "raw_official_sha256":raw_off,"raw_candidate_sha256":raw_fil,
            "normalized_official_sha256":norm_off,"normalized_candidate_sha256":norm_fil,
            "byte_equal_after_allowed_normalization":norm_off==norm_fil,
            "e8_acceptance":("PASS" if norm_off==norm_fil else "FAIL") if a.gate=="B" else ("PASS" if a.candidate_is_integrated_oem and norm_off==norm_fil else "NOT_VALID_E8_CANDIDATE" if not a.candidate_is_integrated_oem else "FAIL") if a.gate=="C" else "NEGATIVE_CONTROL",
            "first_difference":first_difference(a.official,a.filuna),
            "section_differences":{key:first_difference(a.official,a.filuna,key) for key in ("HEADER","CONFIG","EXEC")}}
    a.out.parent.mkdir(parents=True,exist_ok=True)
    a.out.write_text(json.dumps(result,ensure_ascii=False,indent=2)+"\n")
    print(json.dumps(result,ensure_ascii=False,indent=2))
    return 0 if result["e8_acceptance"]=="PASS" else 1

if __name__=="__main__":raise SystemExit(main())
