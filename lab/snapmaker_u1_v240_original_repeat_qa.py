#!/usr/bin/env python3
"""Reference differential: official Snapmaker 2.4.0 Windows portable U1 CLI 30x.

Read ALL v2.4.0 profiles from the SAME exact SHA-verified portable ZIP,
then resolve machine/process/Generic PLA inheritance. No 2.4.1 profiles
are loaded. 2.4.0 is NOT automatically safe/homologated or adopted by Filuna.
A temporary nozzle-bore guard is permitted only in QA with provenance,
to prevent unrelated process-only missing-nozzle C++ crash. All toolpath
changes after exact header timestamp removal remain unreconciled failures.
"""
from __future__ import annotations
import argparse
import hashlib
import json
from pathlib import Path
import re
import sys
from portable_first_qa import obtain,extract_executable,digest
from snapmaker_runtime_nozzle_guard_qa import guarded_runtime_process
from snapmaker_u1_guard_probe import run_cli

ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/"FILUNA"/"tools"))
from oem_universal_inventory import read_catalog

OFFICIAL_240={
 "version":"2.4.0",
 "repo":"Snapmaker/OrcaSlicer",
 "asset":"Snapmaker_Orca_Windows_V2.4.0_portable.zip",
 "tag":"v2.4.0",
 "sha256":"089b7ca20ccfc4be57ffb5a7f9f81e3a2b55db3a9622755fee2b20208bfcb8c2",
 "exe":"snapmaker-orca.exe"
}
MODEL={
 "machine":"Snapmaker U1 (0.4 nozzle)",
 "process":"0.20mm Standard @Snapmaker U1 (0.4 nozzle)",
 "filament":"Generic PLA"
}
DATE_240=re.compile(
 rb"^; generated by Snapmaker Orca 2\.4\.0 on "
 rb"(\d{4}-\d{2}-\d{2}) at (\d{2}:\d{2}:\d{2})\r?\n?$"
)


def official_normalized_sha(data):
    lines=data.splitlines(keepends=True)
    if not lines or lines[0].rstrip(b"\r\n")!=b"; HEADER_BLOCK_START":
        raise ValueError("OFFICIAL_240_HEADER_START_REQUIRED")
    try:
        end=next(i for i,x in enumerate(lines) if x.rstrip(b"\r\n")==b"; HEADER_BLOCK_END")
    except StopIteration:
        raise ValueError("OFFICIAL_240_HEADER_END_REQUIRED")
    if not 1<end<100:raise ValueError("OFFICIAL_240_HEADER_BOUNDARIES_INVALID")
    match=[i for i in range(1,end) if DATE_240.fullmatch(lines[i])]
    if len(match)!=1:raise ValueError("OFFICIAL_240_ONE_GENERATED_AT_LINE_REQUIRED")
    i=match[0]
    clean=b"".join(x for j,x in enumerate(lines) if j!=i)
    return hashlib.sha256(clean).hexdigest()


def resolve(catalog,out):
    files={};metadata={}
    for kind,name in MODEL.items():
        key=kind+":"+name
        r=catalog["profiles"].get(key)
        if not r or r["status"]!="RESOLVED":
            raise ValueError("OFFICIAL_240_EXACT_PROFILE_NOT_RESOLVED "+key)
        payload=dict(r["effective"])
        # Metadata only: inherit was already merged in read_catalog.
        payload.pop("inherits",None)
        payload.pop("renamed_from",None)
        if payload.get("name")!=name or payload.get("type")!=kind:
            raise ValueError("OFFICIAL_240_CONFIG_IDENTITY_MISMATCH")
        dest=out/("effective-"+kind+".json")
        dest.write_text(json.dumps(payload,ensure_ascii=False,indent=2)+"\n",encoding="utf-8")
        files[kind]=dest
        metadata[kind]={"leaf_source":r["file"],"source_sha256":r["source_sha256"],
                        "effective_sha256":digest(dest),"parents":r["parents"]}
    if MODEL["machine"] not in catalog["profiles"]["process:"+MODEL["process"]]["effective"].get("compatible_printers",[]):
        raise ValueError("OFFICIAL_240_MACHINE_PROCESS_INCOMPATIBLE")
    if MODEL["machine"] not in catalog["profiles"]["filament:"+MODEL["filament"]]["effective"].get("compatible_printers",[]):
        raise ValueError("OFFICIAL_240_MACHINE_FILAMENT_INCOMPATIBLE")
    (out/"exact-official-240-profile-chain.json").write_text(json.dumps(metadata,indent=2,ensure_ascii=False)+"\n")
    return files


def main():
    a=argparse.ArgumentParser()
    a.add_argument("--cache",type=Path,default=Path(".oem-snapmaker-240-cache"))
    a.add_argument("--out",type=Path,default=Path("qa-snapmaker-240-official-30"))
    a.add_argument("--runs",type=int,default=30)
    args=a.parse_args()
    if not 2<=args.runs<=50:raise ValueError("INVALID_RUN_COUNT")
    out=args.out.resolve();cache=args.cache.resolve()
    out.mkdir(parents=True,exist_ok=True);cache.mkdir(parents=True,exist_ok=True)
    rows=[];result="FAIL_NOT_RUN"
    provenance={}
    try:
        zipfile,url=obtain(OFFICIAL_240,cache)
        if digest(zipfile)!=OFFICIAL_240["sha256"]:
            raise ValueError("WRONG_VENDOR_RELEASE_SHA")
        exe=extract_executable(zipfile,OFFICIAL_240["exe"],cache/"official-240-extracted").resolve()
        candidates=[x for x in (cache/"official-240-extracted").rglob("Snapmaker")
                    if x.is_dir() and x.parent.name=="profiles"
                    and all((x/s).is_dir() for s in ("machine","process","filament"))]
        if len(candidates)!=1:
            raise ValueError("EXPECTED_ONE_ORIGINAL_240_PROFILE_ROOT got="+str(len(candidates)))
        catalog=read_catalog(candidates[0])
        if catalog["issues"]:
            raise ValueError("ORIGINAL_240_PROFILE_TREE_NOT_RESOLVED")
        profile=resolve(catalog,out)
        proc=out/"process-with-qa-only-nozzle-guard.json"
        guard=guarded_runtime_process(profile["machine"],profile["process"],proc)
        provenance={"official_zip_sha256":digest(zipfile),"source":url,
                    "version":"2.4.0",
                    "original_tree":str(candidates[0].relative_to(cache/"official-240-extracted")),
                    "full_profile_counts":catalog["profiles_per_type"],
                    "machine_preset_count":len(catalog["machines"]),
                    "guard_scope":"temporary process-only nozzle fallback, never production",
                    "nozzle_guard":guard,
                    "source_profile_shas":{k:digest(x) for k,x in profile.items()}}
        for i in range(args.runs):
            label="original240-"+str(i).zfill(2)
            r=run_cli(exe,profile["machine"],proc,profile["filament"],
                      ROOT/"fixtures/cube20.stl",out,label)
            x={"attempt":i,"exit":r["exit_code"],"files":len(r["gcodes"])}
            if r["exit_code"]!=0 or len(r["gcodes"])!=1:
                x["status"]="FAIL_CLI"
                rows.append(x)
                print("SNAPMAKER_240 RUN",i,"FAIL_CLI",x,flush=True)
                break
            g=out/r["gcodes"][0]["path"]
            x.update({"status":"PASS_CLI_OUTPUT","bytes":g.stat().st_size,
                      "normalized_gcode_sha256":official_normalized_sha(g.read_bytes()),
                      "raw_sha256":digest(g),"path":str(g.relative_to(out))})
            rows.append(x)
            print("SNAPMAKER_240 RUN",i,x["bytes"],x["normalized_gcode_sha256"],flush=True)
        counts={}
        for r in rows:
            h=r.get("normalized_gcode_sha256")
            if h:counts[h]=counts.get(h,0)+1
        result="PASS_240_STABLE_IN_"+str(args.runs)+"_ORIGINAL_CLI_RUNS" if (
            len(rows)==args.runs and len(counts)==1 and all(
                r["status"]=="PASS_CLI_OUTPUT" for r in rows)) else "FAIL_240_VARIANCE_OR_CLI"
        provenance.update({"result":result,"attempts_completed":len(rows),
                           "distinct_normalized_gcodes":len(counts),"sha_histogram":counts,
                           "runs":rows,
                           "scope":"Original 2.4.0 U1 CLI only, not Filuna native or physical."})
    except Exception as ex:
        result="FAIL_RUNNER_"+type(ex).__name__
        provenance["exception"]=str(ex)
    (out/"report.json").write_text(json.dumps(provenance,indent=2,ensure_ascii=False)+"\n",encoding="utf-8")
    (out/"RESUMO.md").write_text("# Snapmaker official Windows 2.4.0 U1 reproducibility\n\n"
        "**"+result+"**. Comparing across two OEM generations requires strict same-generation "
        "profiles; this runner tests only the original 2.4.0 30x. "
        "No source/Filuna/native/network/security/physical homologation.\n",encoding="utf-8")
    print("SNAPMAKER_240 RESULT",result,flush=True)
    return 0 if result.startswith("PASS_") else 1

if __name__=="__main__":
    raise SystemExit(main())
