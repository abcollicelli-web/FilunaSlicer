#!/usr/bin/env python3
"""Filuna — paridade do motor de um fabricante: binário compilado da fonte fixada × binário oficial.

Para CADA impressora selecionável do catálogo oficial, fatia as mesmas entradas nos dois binários,
com o trio padrão máquina/processo/filamento resolvido dos perfis do PRÓPRIO oficial,
pasta de dados nova a cada execução, e compara o G-code. Só a linha de cabeçalho com
gerador/data é normalizada (regra §5.1 de REGRA-CANONICA-MODULOS-FABRICANTE-SOB-DEMANDA).

Também roda o oficial duas vezes (A/B): se o próprio oficial varia, qualquer variante oficial
registrada é aceita para o compilado (mesma regra §5.1).

Uso (dentro do contêiner com as bibliotecas de execução):
  paridade.py --id snapmaker --vendor Snapmaker --oficial /x/oficial/squashfs-root/AppRun \
              --compilado /x/compilado/squashfs-root/AppRun --perfis /x/oficial/squashfs-root/resources/profiles \
              --saida /x/resultado [--limite 0]
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from perfis import Catalogo  # noqa: E402

CABECALHO = re.compile(rb"^; generated by .* on \d{4}-\d{2}-\d{2} at \d{2}:\d{2}:\d{2}.*$|^; HEADER_BLOCK_START.*$", re.I)
DATA_LIVRE = re.compile(rb"^;\s*(generated|created) (by|on|at)\b.*$", re.I)


def normalizado(p: Path) -> bytes:
    linhas = []
    for ln in p.read_bytes().splitlines():
        if CABECALHO.match(ln) or DATA_LIVRE.match(ln):
            linhas.append(b"; <cabecalho-normalizado>")
        else:
            linhas.append(ln)
    return b"\n".join(linhas)


# Linhas que só registram estimativas (tempo, filamento total, progresso) — derivam da ordem
# dos trechos e variam quando o próprio oficial reordena trechos de uma camada.
ESTIMATIVA = re.compile(rb"^(M73\b|; (model printing time|total estimated time|estimated printing time|total filament|filament used|"
                        rb"total layer|total filament (length|volume|weight)|filament cost|estimated first layer)\b)", re.I)
CAMADA = re.compile(rb"^(;LAYER_CHANGE|; CHANGE_LAYER|;LAYER:|; layer num/total_layer_count)", re.I)


def canonico(b: bytes) -> str:
    """Impressão digital funcional: por camada, o multiconjunto das linhas (fora estimativas).
    Igual = mesmas instruções em cada camada, só em ordem possivelmente diferente dentro dela.
    Qualquer coordenada, extrusão, temperatura ou comando diferente muda o resultado."""
    h = hashlib.sha256()
    camada: list[bytes] = []

    def fecha():
        for ln in sorted(camada):
            h.update(ln + b"\n")
        h.update(b"--camada--\n")
        camada.clear()

    for ln in b.split(b"\n"):
        if ESTIMATIVA.match(ln):
            continue
        if CAMADA.match(ln):
            fecha()
        camada.append(ln)
    fecha()
    return h.hexdigest()


def sha(b: bytes) -> str:
    return hashlib.sha256(b).hexdigest()


def primeira_diferenca(a: bytes, b: bytes):
    la, lb = a.split(b"\n"), b.split(b"\n")
    for i, (x, y) in enumerate(zip(la, lb), 1):
        if x != y:
            return {"linha": i, "compilado": x[:200].decode("utf-8", "replace"), "oficial": y[:200].decode("utf-8", "replace")}
    if len(la) != len(lb):
        return {"linha": min(len(la), len(lb)) + 1, "linhas_compilado": len(la), "linhas_oficial": len(lb)}
    return None


_AJUDA: dict[str, bytes] = {}


def ajuda(exe: Path) -> bytes:
    k = str(exe)
    if k not in _AJUDA:
        try:
            r = subprocess.run([k, "--help"], capture_output=True, timeout=120, check=False,
                               env=dict(os.environ, HOME="/tmp/filuna-help-home"))
            _AJUDA[k] = r.stdout + r.stderr
        except (OSError, subprocess.TimeoutExpired):
            _AJUDA[k] = b"--datadir"
    return _AJUDA[k]


def aceita_datadir(exe: Path) -> bool:
    """Nem todo CLI de fabricante tem --datadir (QIDI Studio 2.07 não tem); sem ele a pasta de
    dados nova vem do HOME novo de cada execução."""
    return b"--datadir" in ajuda(exe)


def fatiar(exe: Path, trio: dict, modelo: Path, pasta: Path, extra: list[str], timeout: int) -> dict:
    if pasta.exists():
        shutil.rmtree(pasta)
    pasta.mkdir(parents=True)
    dados = pasta / "datadir"
    dados.mkdir()
    n = int(trio.get("n_filamentos") or 1)
    # o 3MF de cores é exportado pelo próprio oficial e grava a versão do app (ex.: Snapmaker 2.4.0.1),
    # que o CLI compara com a versão do motor (01.10.01.50) e recusa como "mais novo"
    novo = ["--allow-newer-file", "1"] if str(modelo).endswith(".3mf") and b"--allow-newer-file" in ajuda(exe) else []
    cmd = [str(exe), *extra, *novo, *(["--datadir", str(dados)] if aceita_datadir(exe) else []), "--slice", "0",
           "--load-settings", f"{trio['machine']};{trio['process']}",
           "--load-filaments", ";".join([str(trio["filament"])] * n),
           "--outputdir", str(pasta), str(modelo)]
    log = pasta / "cli.log"
    t0 = time.time()
    env = dict(os.environ, HOME=str(pasta / "home"), XDG_CONFIG_HOME=str(pasta / "home/.config"))
    with log.open("w", encoding="utf-8", errors="replace") as f:
        f.write("CMD=" + json.dumps(cmd, ensure_ascii=False) + "\n")
        f.flush()
        try:
            rc = subprocess.run(cmd, stdout=f, stderr=subprocess.STDOUT, timeout=timeout, env=env, check=False).returncode
        except subprocess.TimeoutExpired:
            rc = 124
            f.write("\nTIMEOUT\n")
    gcodes = sorted(p for p in pasta.rglob("*.gcode") if "datadir" not in p.parts)
    return {"rc": rc, "segundos": round(time.time() - t0, 1), "gcodes": [str(g) for g in gcodes]}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--id", required=True)
    ap.add_argument("--vendor", required=True, help="pasta do fabricante em resources/profiles (ex.: Snapmaker, BBL)")
    ap.add_argument("--oficial", type=Path, required=True)
    ap.add_argument("--compilado", type=Path, required=True)
    ap.add_argument("--perfis", type=Path, required=True)
    ap.add_argument("--modelo", type=Path, required=True)
    ap.add_argument("--modelo-cores", type=Path, default=None, help="3MF com 4 objetos em extrusoras 1..4")
    ap.add_argument("--saida", type=Path, required=True)
    ap.add_argument("--limite", type=int, default=0)
    ap.add_argument("--timeout", type=int, default=300)
    ap.add_argument("--extra", default="", help="argumentos extras da CLI do fabricante (ex.: '--arrange 1')")
    ap.add_argument("--extra-cores", default="--arrange 1", help="argumentos extras só no caso de 4 cores")
    ap.add_argument("--max-oficial", type=int, default=6, help="execuções do oficial para juntar variantes quando ele não repete")
    ap.add_argument("--max-oficial-busca", type=int, default=12, help="teto de execuções do oficial procurando a variante do compilado")
    ap.add_argument("--cores-todas", action="store_true",
                    help="caso de 4 cores também em máquinas de 1 extrusora (AMS/CFS/IFS/ACE/Box: troca de filamento)")
    ns = ap.parse_args()

    out = ns.saida
    out.mkdir(parents=True, exist_ok=True)
    cat = Catalogo(ns.perfis)
    aud = cat.auditoria()
    impressoras = cat.impressoras(ns.vendor)
    if ns.limite:
        impressoras = impressoras[: ns.limite]
    extra = ns.extra.split() if ns.extra else []
    resultados = []
    for idx, imp in enumerate(impressoras, 1):
        r = {"maquina": imp["maquina"], "processo": imp.get("processo"), "filamento": imp.get("filamento"), "notas": imp.get("notas", [])}
        if imp.get("erro") or not imp.get("processo") or not imp.get("filamento"):
            r["veredito"] = "PERFIL_INCOMPLETO"
            r["detalhe"] = imp.get("erro") or "sem processo/filamento padrão no perfil da máquina"
            resultados.append(r)
            continue
        caso = out / "casos" / f"{idx:03d}"
        try:
            trio = cat.gravar_trio(imp, caso / "perfis")
        except ValueError as e:
            r["veredito"] = "PERFIL_INCOMPLETO"
            r["detalhe"] = str(e)
            resultados.append(r)
            continue
        modelos = [("cubo", ns.modelo, 1)]
        if ns.modelo_cores and (ns.cores_todas or imp.get("extrusoras", 1) >= 2):
            modelos.append(("cores", ns.modelo_cores, 4))
        r["casos"] = []
        for nome_m, modelo, n_fil in modelos:
            t = {"machine": trio["machine"], "process": trio["process"], "filament": trio["filament"], "n_filamentos": n_fil}
            ex = extra + (ns.extra_cores.split() if nome_m == "cores" and ns.extra_cores else [])
            def ok(x):
                return x["rc"] == 0 and len(x["gcodes"]) == 1

            oficiais = [fatiar(ns.oficial, t, modelo, caso / f"{nome_m}-oficial-{k}", ex, ns.timeout) for k in "AB"]
            variantes: dict[str, bytes] = {}

            def registra(x):
                if ok(x):
                    n = normalizado(Path(x["gcodes"][0]))
                    variantes.setdefault(sha(n), n)

            for x in oficiais:
                registra(x)
            # o próprio oficial variou: junta as variantes que ele produz (regra §5.1 aceita qualquer uma)
            k = 2
            while len(variantes) > 1 and k < ns.max_oficial:
                antes = len(variantes)
                x = fatiar(ns.oficial, t, modelo, caso / f"{nome_m}-oficial-{k + 1}", ex, ns.timeout)
                oficiais.append(x); registra(x); k += 1
                if len(variantes) == antes and k >= 4:
                    break
            cc = fatiar(ns.compilado, t, modelo, caso / f"{nome_m}-compilado", ex, ns.timeout)
            oa, ob = oficiais[0], oficiais[1]
            c = {"modelo": nome_m, "oficial_A": oa, "oficial_B": ob, "compilado": cc}
            if ok(cc) and variantes:
                nc = normalizado(Path(cc["gcodes"][0]))
                # variante do compilado ainda não vista: dá mais chances ao oficial antes de reprovar
                # (o oficial pode repetir A=B e variar só depois: o Bambu faz isso; por isso procura
                # mesmo com uma variante, até max_oficial, e até max_oficial_busca se já variou)
                while sha(nc) not in variantes and k < (ns.max_oficial_busca if len(variantes) > 1 else ns.max_oficial):
                    x = fatiar(ns.oficial, t, modelo, caso / f"{nome_m}-oficial-{k + 1}", ex, ns.timeout)
                    oficiais.append(x); registra(x); k += 1
            c["execucoes_oficiais"] = len(oficiais)
            c["variantes_oficiais"] = len(variantes)
            falha_a = not ok(oa)
            falha_c = not ok(cc)
            if falha_a and falha_c and oa["rc"] == cc["rc"]:
                # o binário oficial recusa este caso e o compilado recusa igual: mesmo comportamento
                c["veredito"] = "MESMA_RECUSA_DO_OFICIAL"
            elif falha_a:
                c["veredito"] = "OFICIAL_NAO_FATIOU"
            elif falha_c:
                c["veredito"] = "COMPILADO_NAO_FATIOU"
            else:
                na = variantes[next(iter(variantes))]
                c["sha_oficial"] = sorted(variantes)
                c["sha_compilado"] = sha(nc)
                c["bytes"] = len(nc)
                c["oficial_repete"] = len(variantes) == 1
                c["canonico_compilado"] = canonico(nc)
                c["canonico_oficial"] = sorted({canonico(v) for v in variantes.values()})
                if sha(nc) in variantes:
                    c["veredito"] = "IDENTICO"
                else:
                    c["veredito"] = "DIVERGE"
                    mais_perto = min(variantes.values(), key=lambda v: abs(len(v) - len(nc)))
                    c["primeira_diferenca"] = primeira_diferenca(nc, mais_perto)
                # trocas de ferramenta/filamento (sistema de cores) contadas no G-code oficial
                c["trocas_ferramenta"] = len(re.findall(rb"^(T\d+|M620 S\d+)\b", na, re.M))
            r["casos"].append(c)
        vs = [c["veredito"] for c in r["casos"]]
        aceitos = ("IDENTICO", "MESMA_RECUSA_DO_OFICIAL")
        r["veredito"] = ("IDENTICO" if vs and all(v == "IDENTICO" for v in vs)
                         else next((v for v in vs if v not in aceitos), "IDENTICO_COM_RECUSA_OFICIAL"))
        resultados.append(r)
        print(f"[{idx}/{len(impressoras)}] {r['veredito']:22} {imp['maquina']}", flush=True)

    resumo = {}
    for r in resultados:
        resumo[r["veredito"]] = resumo.get(r["veredito"], 0) + 1
    prova = {"id": ns.id, "vendor": ns.vendor, "oficial": str(ns.oficial), "compilado": str(ns.compilado),
             "auditoria_perfis": aud, "impressoras": len(impressoras), "resumo": resumo, "resultados": resultados}
    (out / "prova.json").write_text(json.dumps(prova, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print("RESUMO " + json.dumps(resumo, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    sys.exit(main())
