#!/usr/bin/env python3
"""Only proven generated-at header timestamp is nonsemantic in Anycubic 2.0.0.6.

Fail closed for every other OEM G-code byte: geometry, paths, extrusion,
feed, purge, temperature, line endings, machine identity, filename or version.
"""
from __future__ import annotations
import hashlib
import json
from pathlib import Path
import re

STAMP=re.compile(rb"; generated by AnycubicSlicerNext 2\.0\.0\.6 on "
                 rb"\d{4}-\d{2}-\d{2} at \d{2}:\d{2}:\d{2}")

def strict_original_gcode_ab(a:bytes,b:bytes)->dict:
    lines_a=a.splitlines(keepends=True);lines_b=b.splitlines(keepends=True)
    r={"manufacturer":"Anycubic","official_version":"2.0.0.6",
       "raw_sha_a":hashlib.sha256(a).hexdigest(),
       "raw_sha_b":hashlib.sha256(b).hexdigest(),
       "bytes_a":len(a),"bytes_b":len(b),
       "lines_a":len(lines_a),"lines_b":len(lines_b),
       "allow":"ONLY line 2 generated-at timestamp in OEM HEADER_BLOCK",
       "no_toolpath_normalization":True}
    if not lines_a or len(lines_a)!=len(lines_b):
        r["status"]="FAIL_LINE_COUNT_MISMATCH";return r
    if a==b:
        r["status"]="PASS_RAW_SHA256_IDENTICAL"
        r["normalized_sha256"]=hashlib.sha256(a).hexdigest()
        return r
    diffs=[i for i,(x,y) in enumerate(zip(lines_a,lines_b)) if x!=y]
    r["changed_lines"]=[i+1 for i in diffs[:40]]
    if diffs!=[1]:
        r["status"]="FAIL_UNAUTHORIZED_GCODE_CHANGE"
        return r
    def splitnl(s):
        if s.endswith(b"\r\n"):return s[:-2],b"\r\n"
        if s.endswith(b"\n"):return s[:-1],b"\n"
        return s,b""
    a2,nla=splitnl(lines_a[1]);b2,nlb=splitnl(lines_b[1])
    has_header=(lines_a[0].rstrip(b"\r\n")==b"; HEADER_BLOCK_START" and
                lines_b[0].rstrip(b"\r\n")==b"; HEADER_BLOCK_START" and
                any(x.rstrip(b"\r\n")==b"; HEADER_BLOCK_END" for x in lines_a[2:70]) and
                any(x.rstrip(b"\r\n")==b"; HEADER_BLOCK_END" for x in lines_b[2:70]))
    if not (has_header and nla and nla==nlb and
            STAMP.fullmatch(a2) is not None and STAMP.fullmatch(b2) is not None):
        r["status"]="FAIL_INVALID_HEADER_TIMESTAMP";return r
    x=b"".join(lines_a[:1]+lines_a[2:]);y=b"".join(lines_b[:1]+lines_b[2:])
    if x!=y:
        r["status"]="FAIL_UNAPPROVED_BODY_VARIANCE";return r
    r["status"]="PASS_ONLY_VERIFIED_GENERATED_AT_TIMESTAMP"
    r["normalized_sha256"]=hashlib.sha256(x).hexdigest()
    r["actual_a"]=a2.decode("ascii");r["actual_b"]=b2.decode("ascii")
    return r

def compare_files(a:Path,b:Path,proof:Path)->dict:
    r=strict_original_gcode_ab(a.read_bytes(),b.read_bytes())
    proof.parent.mkdir(parents=True,exist_ok=True)
    proof.write_text(json.dumps(r,indent=2,ensure_ascii=False)+"\n",encoding="utf-8")
    return r
