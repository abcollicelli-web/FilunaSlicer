#!/usr/bin/env python3
"""Positive and deliberately adversarial Anycubic official G-code comparator QA."""
import unittest
from anycubic_original_gcode_strict import strict_original_gcode_ab

START=(b"; HEADER_BLOCK_START\n"
       b"; generated by AnycubicSlicerNext 2.0.0.6 on 2026-11-07 at 01:01:15\n"
       b"; total layer number: 2\n"
       b"; HEADER_BLOCK_END\n"
       b"G1 X10 Y10 E0.43 F3000\n"
       b"M104 S210\n")
OTHER=START.replace(b"01:01:15",b"01:01:16")

class StrictOriginalGcodeAB(unittest.TestCase):
    def test_identical_raw(self):
        self.assertEqual(strict_original_gcode_ab(START,START)["status"],
                         "PASS_RAW_SHA256_IDENTICAL")
    def test_only_actual_generated_at_time(self):
        r=strict_original_gcode_ab(START,OTHER)
        self.assertEqual(r["status"],"PASS_ONLY_VERIFIED_GENERATED_AT_TIMESTAMP")
        self.assertEqual(r["changed_lines"],[2])
    def test_reject_movement_difference(self):
        self.assertTrue(strict_original_gcode_ab(
            START,OTHER.replace(b"X10",b"X11"))["status"].startswith("FAIL"))
    def test_reject_temperature_difference(self):
        self.assertTrue(strict_original_gcode_ab(
            START,OTHER.replace(b"S210",b"S260"))["status"].startswith("FAIL"))
    def test_reject_other_version(self):
        self.assertEqual(strict_original_gcode_ab(
            START,OTHER.replace(b"Next 2.0.0.6",b"Next 2.0.0.7"))["status"],
            "FAIL_INVALID_HEADER_TIMESTAMP")
    def test_reject_newline_difference(self):
        self.assertTrue(strict_original_gcode_ab(
            START,OTHER.replace(b"\n",b"\r\n"))["status"].startswith("FAIL"))
    def test_reject_wrong_header_location(self):
        self.assertEqual(strict_original_gcode_ab(
            START,OTHER.replace(b"HEADER_BLOCK_START",b"WRONG_BLOCK_START"))["status"],
            "FAIL_UNAUTHORIZED_GCODE_CHANGE")
    def test_reject_different_line_counts(self):
        self.assertEqual(strict_original_gcode_ab(
            START,OTHER+b"M73 P10 R5\n")["status"],"FAIL_LINE_COUNT_MISMATCH")
if __name__=="__main__":unittest.main()
