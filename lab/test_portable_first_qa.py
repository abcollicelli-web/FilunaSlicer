#!/usr/bin/env python3
"""Offline regression cases: no false equivalence from dynamic-header normalization."""
from pathlib import Path
import tempfile
import unittest

from portable_first_qa import compare_official_a_b

HEADER_A=b"; generated by ElegooSlicer 1.5.3.5 on 2026-11-06 at 22:58:48\n"
HEADER_B=b"; generated by ElegooSlicer 1.5.3.5 on 2026-11-06 at 22:58:49\n"

class StrictOfficialParityTests(unittest.TestCase):
 def compare(self,a,b,brand="elegoo",version="1.5.3.5"):
  with tempfile.TemporaryDirectory() as tmp:
   root=Path(tmp)
   first=root/"A.gcode";second=root/"B.gcode"
   first.write_bytes(a);second.write_bytes(b)
   status,reason=compare_official_a_b(brand,version,first,second,root)
   self.assertTrue((root/"official-A-B-proof.json").is_file())
   return status,reason

 def test_exact_raw_identity(self):
  a=b"; header\n"+HEADER_A+b"G1 X1 Y1 E0.2\n"
  status,reason=self.compare(a,a)
  self.assertEqual(status,"PASS");self.assertIn("RAW_SHA_IDENTICAL",reason)

 def test_only_proven_elegoo_header_timestamp(self):
  a=b"; header\n"+HEADER_A+b"G1 X1 Y1 E0.2\n"
  b=b"; header\n"+HEADER_B+b"G1 X1 Y1 E0.2\n"
  status,reason=self.compare(a,b)
  self.assertEqual(status,"PASS");self.assertIn("lines=[2]",reason)

 def test_toolpath_difference_rejected(self):
  a=b"; header\n"+HEADER_A+b"G1 X1 Y1 E0.2\n"
  b=b"; header\n"+HEADER_B+b"G1 X1 Y1 E0.3\n"
  status,_=self.compare(a,b)
  self.assertEqual(status,"FAIL")

 def test_other_brand_does_not_inherit_elegoo_exception(self):
  a=b"; header\n"+HEADER_A+b"G1 X1\n"
  b=b"; header\n"+HEADER_B+b"G1 X1\n"
  self.assertEqual(self.compare(a,b,brand="qidi")[0],"FAIL")

 def test_other_version_does_not_inherit_exception(self):
  a=b"; header\n"+HEADER_A+b"G1 X1\n"
  b=b"; header\n"+HEADER_B+b"G1 X1\n"
  self.assertEqual(self.compare(a,b,version="1.5.3.6")[0],"FAIL")

 def test_header_line_position_required(self):
  a=b"; header\n; other\n"+HEADER_A+b"G1 X1\n"
  b=b"; header\n; other\n"+HEADER_B+b"G1 X1\n"
  self.assertEqual(self.compare(a,b)[0],"FAIL")

 def test_number_of_lines_must_match(self):
  a=b"; header\n"+HEADER_A+b"G1 X1\n"
  b=b"; header\n"+HEADER_B+b"G1 X1\nG1 X2\n"
  self.assertEqual(self.compare(a,b)[0],"FAIL")

 def test_non_timestamp_header_change_not_permitted(self):
  a=b"; header\n"+HEADER_A+b"G1 X1\n"
  b=b"; HEADER MUTATED\n"+HEADER_B+b"G1 X1\n"
  self.assertEqual(self.compare(a,b)[0],"FAIL")

if __name__=="__main__":
 unittest.main()
