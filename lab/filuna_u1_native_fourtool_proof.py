#!/usr/bin/env python3
"""Snapmaker U1 four-tool proof with the FILUNA executable (not the OEM one).

Inputs are identical to the OEM 20-run stress (run 42396616586): same synthetic
four-tool Core 3MF, same effective official v2.4.1 presets, same QA nozzle guard.
Outputs (read-only analysis, G-code never rewritten):
  1. Filuna CLI exit code + G-code SHA, tools T0-T3, toolchange count
  2. Final-purge Z-lift: first Z rise vs first XY travel after the last toolchange block
  3. Python spatial validator decision (must be PASS, no collision)
  4. Functional comparison against OEM variants A (1fffba21) and B (b42e9a25)
NOT network/ACK, NOT firmware, NOT physical, NOT release.
"""
from __future__ import annotations
import argparse, difflib, hashlib, json, re, shutil, subprocess, sys
from pathlib import Path

from snapmaker_u1_inherit import build_effective_original_presets
from snapmaker_runtime_nozzle_guard_qa import guarded_runtime_process
from snapmaker_u1_guard_probe import list_gcodes
from snapmaker_u1_fourtool_original_qa import build_minimal_core_3mf, build_four_from_core_3mf
from snapmaker_u1_temporal_ab_qa import header_date_only_normalization
from snapmaker_spatial_gcode_validator import policy_from_yaml, validate_gcode

ROOT = Path(__file__).resolve().parents[1]
OEM_A = "1fffba21d2cce0e0456f69836e3e8b5f22aaa35e955ddcb8305627457aca12d1"
OEM_B = "b42e9a25f5440cf7e0b7d422f36855506c8ed71a2a73e7f66dd1b479d401fa7a"
MOVE = re.compile(rb"^G[0-3](?=\s|$)")
NUM = lambda axis: re.compile(rb"\b" + axis + rb"(-?\d*\.?\d+)")
RX, RY, RZ, RE_ = NUM(b"X"), NUM(b"Y"), NUM(b"Z"), NUM(b"E")


def functional_lines(data: bytes) -> list[bytes]:
    """Drop comments/blank lines and the HEADER_BLOCK 'generated by' line only."""
    out = []
    for raw in data.splitlines():
        if b"generated by" in raw and raw.lstrip().startswith(b";"):
            continue
        code = raw.split(b";", 1)[0].strip()
        if code:
            out.append(code)
    return out


def final_purge_lift(data: bytes) -> dict:
    """After the LAST '; CP TOOLCHANGE START', require Z to rise above the
    current layer Z before the first non-extruding XY travel."""
    lines = data.splitlines()
    starts = [i for i, l in enumerate(lines) if l.strip().startswith(b"; CP TOOLCHANGE START")]
    if not starts:
        return {"status": "FAIL_NO_TOOLCHANGE_BLOCK"}
    marker = starts[-1]
    # Last positive extrusion on the part before the final block = where the nozzle leaves the print.
    z, last_print = None, None
    for idx in range(marker):
        code = lines[idx].split(b";", 1)[0].strip()
        if not MOVE.match(code):
            continue
        mz = RZ.search(code)
        if mz:
            z = float(mz.group(1))
        me = RE_.search(code)
        if me and float(me.group(1)) > 0 and (RX.search(code) or RY.search(code)):
            last_print, layer_z = idx, z
    if last_print is None:
        return {"status": "FAIL_NO_PRINT_BEFORE_FINAL_BLOCK"}
    # Between leaving the part and the tower block (+ a few lines into it): Z must rise above
    # the layer Z before the first XY travel without extrusion.
    lifted, first_xy, cur_z = None, None, layer_z
    for idx in range(last_print + 1, min(len(lines), marker + 60)):
        code = lines[idx].split(b";", 1)[0].strip()
        if not MOVE.match(code):
            continue
        mz = RZ.search(code)
        if mz:
            cur_z = float(mz.group(1))
            if layer_z is not None and cur_z > layer_z + 1e-6 and lifted is None:
                lifted = {"line": idx + 1, "z": cur_z}
        if (RX.search(code) or RY.search(code)) and not RE_.search(code):
            first_xy = {"line": idx + 1, "z_at_move": cur_z, "text": code.decode(errors="replace")}
            break
    z = layer_z
    ok = lifted is not None and first_xy is not None and lifted["line"] <= first_xy["line"]
    return {"status": "PASS_Z_LIFT_BEFORE_XY" if ok else "FAIL_NO_Z_LIFT_BEFORE_XY",
            "last_toolchange_block_line": starts[-1] + 1, "layer_z_before": z,
            "first_lift": lifted, "first_xy_travel": first_xy}


def compare(filuna: list[bytes], oem: list[bytes]) -> dict:
    sm = difflib.SequenceMatcher(None, filuna, oem, autojunk=False)
    groups = [op for op in sm.get_opcodes() if op[0] != "equal"]
    first = None
    if groups:
        tag, i1, i2, j1, j2 = groups[0]
        first = {"filuna_func_line": i1 + 1, "oem_func_line": j1 + 1,
                 "filuna": [l.decode(errors="replace") for l in filuna[i1:min(i2, i1 + 5)]],
                 "oem": [l.decode(errors="replace") for l in oem[j1:min(j2, j1 + 5)]]}
    moves = lambda ls: sum(1 for l in ls if MOVE.match(l))
    return {"identical": not groups, "edit_groups": len(groups),
            "filuna_moves": moves(filuna), "oem_moves": moves(oem),
            "similarity_ratio": round(sm.ratio(), 6), "first_divergence": first}


def run_filuna_arrange0(exe: Path, machine: Path, process: Path,
                        filament: Path, cube: Path, out: Path, label: str,
                        timeout: int = 600) -> dict:
    """Local copy of run_cli, adding --arrange 0; shared OEM helper untouched."""
    target = out / label
    if target.exists():
        shutil.rmtree(target)
    target.mkdir()
    log = out / (label + ".log")
    settings = str(machine) + ";" + str(process)
    filaments = ";".join([str(filament)] * 4)
    argv = ["--debug", "3", "--arrange", "0", "--slice", "0",
            "--load-settings", settings, "--load-filaments", filaments,
            "--outputdir", str(target), str(cube.resolve())]
    command = [str(exe), *argv]
    with log.open("w", encoding="utf-8", errors="replace") as fp:
        fp.write("COMMAND_JSON=" + json.dumps(command, ensure_ascii=False) + "\n")
        fp.flush()
        try:
            code = subprocess.run(command, cwd=exe.parent, stdout=fp,
                                  stderr=subprocess.STDOUT, timeout=timeout,
                                  check=False).returncode
        except subprocess.TimeoutExpired:
            code = 124
            fp.write("TIMEOUT\n")
    gcodes = list_gcodes(target)
    inventory = {"case": label, "exit_code": code,
                 "gcodes": [{"path": str(p.relative_to(out)), "bytes": p.stat().st_size,
                             "sha256": hashlib.sha256(p.read_bytes()).hexdigest()}
                            for p in gcodes], "log": log.name}
    (out / (label + "-inventory.json")).write_text(json.dumps(inventory, indent=2) + "\n")
    return inventory


def object_defines(data: bytes) -> list[str]:
    return [line.decode(errors="replace") for line in data.splitlines()
            if line.startswith(b"EXCLUDE_OBJECT_DEFINE ")]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--exe", type=Path, required=True)
    ap.add_argument("--oem-a", type=Path, required=True, help="OEM stress-00 plate G-code")
    ap.add_argument("--oem-b", type=Path, required=True, help="OEM stress-09 plate G-code")
    ap.add_argument("--out", type=Path, default=Path("qa-u1-filuna-native"))
    a = ap.parse_args()
    # run_cli executes with cwd=exe.parent, so every preset/3MF path must be absolute.
    a.out = a.out.resolve()
    a.exe, a.oem_a, a.oem_b = a.exe.resolve(), a.oem_a.resolve(), a.oem_b.resolve()
    a.out.mkdir(parents=True, exist_ok=True)
    rep = {"scope": "FILUNA executable, Snapmaker U1 0.4, synthetic 4-tool Core 3MF",
           "exe_sha256": hashlib.sha256(a.exe.read_bytes()).hexdigest(),
           "network_ack": "NOT_RUN", "physical_beta": "NOT_RUN", "status": "NOT_RUN"}
    try:
        for label, p, want in (("A", a.oem_a, OEM_A), ("B", a.oem_b, OEM_B)):
            got = header_date_only_normalization(p.read_bytes())["normalized_sha256"]
            if got != want:
                raise ValueError(f"OEM_REFERENCE_{label}_SHA_MISMATCH {got}")
        prof = build_effective_original_presets(a.out)
        proc = a.out / "qa-process-nozzle-guard.json"
        guarded_runtime_process(prof["machine"], prof["process"], proc)
        # QA-only manufacturer overlay: the pinned official JSON stays byte-for-byte unchanged.
        # The native Filuna Snapmaker module must apply this vendor default in production.
        vendor = json.loads((ROOT / "FILUNA/fabricantes/snapmaker/vendor.yaml").read_text(encoding="utf-8"))
        native_defaults = vendor["filuna_native_defaults"]
        if native_defaults.get("klipper_emit_minimum_cruise_ratio") is not False:
            raise ValueError("SNAPMAKER_U1_MCR_VENDOR_DEFAULT_NOT_FALSE")
        filuna_machine = a.out / "filuna-snapmaker-machine.json"
        machine_cfg = json.loads(prof["machine"].read_text(encoding="utf-8"))
        if machine_cfg.get("tool_change_temprature_wait") not in ("0", 0, False):
            raise ValueError("OEM_U1_TOOLCHANGE_WAIT_NOT_ZERO")
        machine_cfg["klipper_emit_minimum_cruise_ratio"] = "0"
        filuna_machine.write_text(json.dumps(machine_cfg, indent=2) + "\n", encoding="utf-8")
        rep["snapmaker_vendor_defaults"] = {"tool_change_temprature_wait": machine_cfg["tool_change_temprature_wait"],
                                              "klipper_emit_minimum_cruise_ratio": "0",
                                              "source": "FILUNA/fabricantes/snapmaker/vendor.yaml",
                                              "official_preset_modified": False}
        single, four = a.out / "seed-core.3mf", a.out / "four-tools.3mf"
        build_minimal_core_3mf(single)
        build_four_from_core_3mf(single, four)
        # The updated build_four_from_core_3mf fixture already places cubes on OEM A's 2x2 grid.
        run = run_filuna_arrange0(a.exe, filuna_machine, proc, prof["filament"],
                                  four, a.out, "filuna", timeout=600)
        rep["cli"] = run
        rep["arrange_mode"] = "--arrange 0"
        if run["exit_code"] != 0 or len(run["gcodes"]) != 1:
            rep["status"] = "FAIL_FILUNA_CLI_NO_GCODE"
            return 1
        data = (a.out / run["gcodes"][0]["path"]).read_bytes()
        rep["gcode_sha256"] = hashlib.sha256(data).hexdigest()
        rep["tools"] = sorted({int(m.group(1)) for m in re.finditer(rb"(?m)^\s*T([0-3])(?:\s|;|$)", data)})
        rep["toolchange_blocks"] = len(re.findall(rb"(?m)^;\s*CP TOOLCHANGE START", data))
        rep["final_purge"] = final_purge_lift(data)
        risk = validate_gcode(data, policy_from_yaml(ROOT / "FILUNA/fabricantes/snapmaker/vendor.yaml"), source="filuna")
        rep["python_validator"] = {"status": risk["status"], "issues": risk["issues"][:5]}
        fl = functional_lines(data)
        filuna_defines = object_defines(data)
        oem_a_defines = object_defines(a.oem_a.read_bytes())
        oem_b_defines = object_defines(a.oem_b.read_bytes())
        rep["exclude_object_define"] = {
            "filuna": filuna_defines, "oem_A": oem_a_defines, "oem_B": oem_b_defines,
            "side_by_side_A": [{"filuna": filuna_defines[i] if i < len(filuna_defines) else None,
                                "oem_A": oem_a_defines[i] if i < len(oem_a_defines) else None}
                               for i in range(max(len(filuna_defines), len(oem_a_defines)))],
            "side_by_side_B": [{"filuna": filuna_defines[i] if i < len(filuna_defines) else None,
                                "oem_B": oem_b_defines[i] if i < len(oem_b_defines) else None}
                               for i in range(max(len(filuna_defines), len(oem_b_defines)))],
        }
        rep["vs_oem_A"] = compare(fl, functional_lines(a.oem_a.read_bytes()))
        rep["vs_oem_B"] = compare(fl, functional_lines(a.oem_b.read_bytes()))
        safe = rep["python_validator"]["status"] == "PASS" and rep["final_purge"]["status"].startswith("PASS")
        four_ok = rep["tools"] == [0, 1, 2, 3]
        parity = rep["vs_oem_A"]["identical"] or rep["vs_oem_B"]["identical"]
        rep["status"] = ("PASS_SAFE_AND_IDENTICAL" if safe and four_ok and parity else
                         "SAFE_BUT_DIVERGES_FROM_OEM" if safe and four_ok else
                         "FAIL_UNSAFE_OR_INCOMPLETE")
        # Note: identical is not expected - the Z-lift deviation alone changes lines.
        # SAFE_BUT_DIVERGES -> read first_divergence: if it is only at the final purge, the
        # authorized deviation is the only difference; otherwise OEM engine deltas remain.
        return 0
    except Exception as exc:
        rep["status"] = "FAIL_" + type(exc).__name__
        rep["error"] = str(exc)
        return 1
    finally:
        (a.out / "proof.json").write_text(json.dumps(rep, indent=2, ensure_ascii=False) + "\n")
        print(json.dumps({k: rep.get(k) for k in ("status", "gcode_sha256", "tools", "final_purge",
                                                    "python_validator")}, indent=2, default=str))


if __name__ == "__main__":
    sys.exit(main())