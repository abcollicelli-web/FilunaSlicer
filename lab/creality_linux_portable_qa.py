#!/usr/bin/env python3
"""Test official CrealityPrint 7.3.1 Linux AppImage without compiling or installing.

This tests reproducibility of *official* CLI; never claims Filuna OEM parity.
All input files are pinned fixtures derived from prior R3 Creality K2 Plus QA.
"""
from __future__ import annotations
import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys
import urllib.request

ROOT=Path(__file__).resolve().parents[1]
VERSION="7.3.1.6378"
URL=("https://github.com/CrealityOfficial/CrealityPrint/releases/download/v7.3.1/"
     "CrealityPrint-V7.3.1.6378-x86_64-Release.AppImage")
SHA256="f8c8dbf18a6b0d5878961b24490fc20958eefe2f03f6a89f524cb9b21e55a107"
MAX_DOWNLOAD=400*1024*1024
# Only metadata proven to vary between A/B in prior R3 official Creality runs.
AUTHORIZED={
    2:re.compile(rb"; generated by Creality_Print V[0-9.]+ on \d{4}-\d{2}-\d{2} at \d{2}:\d{2}:\d{2}"),
    7:re.compile(rb"; creality_uuid: [0-9a-f-]{36}"),
}
def sha(path:Path)->str:
 h=hashlib.sha256()
 with path.open("rb") as inp:
  for block in iter(lambda:inp.read(1024*1024),b""):h.update(block)
 return h.hexdigest()

def execute(cmd:list[str],log:Path,timeout:int=240,cwd:Path|None=None)->int:
 log.parent.mkdir(parents=True,exist_ok=True)
 with log.open("w",encoding="utf-8",errors="replace") as f:
  f.write("COMMAND="+json.dumps(cmd,ensure_ascii=False)+"\n");f.flush()
  try:
   return subprocess.run(cmd,cwd=cwd,stdout=f,stderr=subprocess.STDOUT,
                         timeout=timeout,check=False).returncode
  except subprocess.TimeoutExpired:
   f.write("TIMEOUT\n");return 124
  except OSError as exc:
   f.write("LAUNCH_ERROR="+repr(exc)+"\n");return 127

def get_package(cache:Path)->Path:
 cache.mkdir(parents=True,exist_ok=True)
 archive=cache/"CrealityPrint-7.3.1.6378-official.AppImage"
 if not archive.exists() or sha(archive)!=SHA256:
  archive.unlink(missing_ok=True)
  partial=archive.with_suffix(".partial")
  partial.unlink(missing_ok=True)
  try:
   req=urllib.request.Request(URL,headers={"User-Agent":"Filuna-OEM-Portable-QA/1"})
   with urllib.request.urlopen(req,timeout=90) as response,partial.open("wb") as dst:
    total=0
    for block in iter(lambda:response.read(1024*1024),b""):
     total+=len(block)
     if total>MAX_DOWNLOAD:raise RuntimeError("UNEXPECTED_ARCHIVE_SIZE")
     dst.write(block)
   if sha(partial)!=SHA256:raise RuntimeError("OFFICIAL_APPIMAGE_SHA_MISMATCH actual="+sha(partial))
   partial.replace(archive)
  finally:
   partial.unlink(missing_ok=True)
 if sha(archive)!=SHA256:raise RuntimeError("CORRUPTED_CACHED_APPIMAGE")
 archive.chmod(archive.stat().st_mode|0o111)
 return archive

def diff_proof(a:Path,b:Path,out:Path)->tuple[str,str]:
 # Byte-exact comparison except metadata proven to vary in official A/B.
 # splitlines(keepends=True) is mandatory: never silently erase CRLF/LF differences.
 la=a.read_bytes().splitlines(keepends=True)
 lb=b.read_bytes().splitlines(keepends=True)
 if len(la)!=len(lb):return "FAIL","GCODE_LINE_COUNT_CHANGED A="+str(len(la))+" B="+str(len(lb))
 changes=[]
 na=[];nb=[]
 def newline(value:bytes)->bytes:
  return b"\r\n" if value.endswith(b"\r\n") else (b"\n" if value.endswith(b"\n") else b"")
 for idx,(aa,bb) in enumerate(zip(la,lb),1):
  if aa!=bb:
   rx=AUTHORIZED.get(idx)
   if (rx is None or newline(aa)!=newline(bb)
       or not rx.fullmatch(aa.rstrip(b"\r\n")) or not rx.fullmatch(bb.rstrip(b"\r\n"))):
    return "FAIL",f"UNAUTHORIZED_GCODE_DIFFERENCE line={idx} A={aa[:160]!r} B={bb[:160]!r}"
   changes.append({"line":idx,"A":aa.rstrip(b"\r\n").decode("utf-8","replace"),
                   "B":bb.rstrip(b"\r\n").decode("utf-8","replace")})
   aa=bb=b"; PROVEN OEM GENERATED VARIABLE"+newline(aa)
  na.append(aa);nb.append(bb)
 proof={"source":"same official CrealityPrint AppImage","version":VERSION,
        "raw_sha_A":sha(a),"raw_sha_B":sha(b),"variable_lines":changes,
        "normalization_scope":"only lines 2/7 IF actually different",
        "line_endings":"preserved byte-exactly except allowed metadata values",
        "normalized_sha_A":hashlib.sha256(b"".join(na)).hexdigest(),
        "normalized_sha_B":hashlib.sha256(b"".join(nb)).hexdigest()}
 (out/"A-B-proof.json").write_text(json.dumps(proof,indent=2)+"\n",encoding="utf-8")
 if na!=nb:return "FAIL","NORMALIZATION_MISMATCH"
 return "PASS",("RAW_IDENTICAL" if not changes else "STRICT_HEADER_ONLY_NORMALIZED")+" sha="+proof["normalized_sha_A"]

def main()->int:
 p=argparse.ArgumentParser()
 p.add_argument("--cache",type=Path,default=Path(".oem-appimage-cache"))
 p.add_argument("--out",type=Path,default=Path("qa-creality-linux"))
 args=p.parse_args()
 out=args.out.resolve();out.mkdir(parents=True,exist_ok=True)
 cache=args.cache.resolve();cache.mkdir(parents=True,exist_ok=True)
 rows=[]
 def add(stage,status,detail):
  assert status in ("PASS","FAIL","PENDING")
  rows.append({"brand":"creality","stage":stage,"status":status,"detail":detail})
  print(f"CREALITY {stage}: {status} — {detail}",flush=True)
 try:
  archive=get_package(cache)
  add("OFFICIAL_APPIMAGE_SHA256","PASS",f"sha256={sha(archive)} bytes={archive.stat().st_size}")
  extracted=cache/"squashfs-root"
  runner=extracted/"AppRun"
  if not runner.is_file():
   extracted.mkdir(parents=True,exist_ok=True)
   rc=execute([str(archive),"--appimage-extract"],out/"appimage-extract.log",180,cwd=cache)
   if rc!=0:raise RuntimeError("OFFICIAL_APPIMAGE_EXTRACT_EXIT "+str(rc))
  if not runner.is_file():raise RuntimeError("APPIMAGE_APPRUN_NOT_FOUND")
  runner.chmod(runner.stat().st_mode|0o111)
  binary=extracted/"bin"/"CrealityPrint"
  if binary.is_file():
   diagnosis=subprocess.run(["ldd",str(binary)],capture_output=True,text=True,timeout=30,check=False)
   (out/"ldd-CrealityPrint.log").write_text(diagnosis.stdout+diagnosis.stderr,encoding="utf-8",errors="replace")
   missing=[line.strip() for line in (diagnosis.stdout+diagnosis.stderr).splitlines() if "not found" in line]
   if missing:raise RuntimeError("OFFICIAL_RUNTIME_LIBRARIES_MISSING "+repr(missing[:15]))
  add("PORTABLE_RUNTIME","PASS","official AppImage extracted without compiling/installing")
  fixture=ROOT/"fixtures"/"oem"/"creality"
  machine=fixture/"resolved-profiles"/"machine.json"
  process=fixture/"resolved-profiles"/"process.json"
  filament=fixture/"resolved-profiles"/"filament.json"
  model=fixture/"cube20.stl"
  for f in (machine,process,filament,model):
   if not f.is_file():raise RuntimeError("OFFICIAL_PROFILE_FIXTURE_MISSING "+str(f))
  (out/"input-sha256.json").write_text(json.dumps(
   {f.name:sha(f) for f in (machine,process,filament,model)},indent=2)+"\n")
  results=[]
  for letter in ("A","B"):
   folder=out/("run-"+letter)
   if folder.exists():shutil.rmtree(folder)
   folder.mkdir(parents=True)
   cmd=["xvfb-run","-a","-s","-screen 0 1920x1080x24",
        str(runner),"--cli","--debug","5","--slice","0","--need-gcode-file",
        "--load-settings",str(machine)+";"+str(process),
        "--load-filaments",str(filament),"--outputdir",str(folder),str(model)]
   rc=execute(cmd,out/("official-"+letter+".log"),240,cwd=extracted)
   files=sorted(folder.rglob("*.gcode"))
   if rc!=0 or len(files)!=1 or files[0].stat().st_size==0:
    add("OFFICIAL_"+letter,"FAIL",f"EXIT={rc} GCODE_FILES={len(files)}; inspect official-{letter}.log")
    add("OFFICIAL_A_B","PENDING","official CLI attempt not completed")
    break
   f=files[0]
   add("OFFICIAL_"+letter,"PASS",f"bytes={f.stat().st_size} sha256={sha(f)}")
   results.append(f)
  if len(results)==2:
   status,details=diff_proof(results[0],results[1],out)
   add("OFFICIAL_A_B",status,details)
  add("FILUNA_PARITY","PENDING","Separate Filuna process was NOT run, not equivalent to official A/B")
  add("NETWORK","PENDING","No Filuna native Creality printer network test")
 except Exception as exc:
  add("RUNNER","FAIL",f"{type(exc).__name__}: {exc}")
 (out/"results.json").write_text(json.dumps(rows,indent=2)+"\n")
 (out/"RESUMO.md").write_text("# Filuna QA: Creality K2 Plus — AppImage oficial\n\n"
  +"**Sem compilação, instalação ou impressão física.**\n\n"
  +"| Gate | Estado | Evidência |\n|---|---|---|\n"
  +"".join(f"| {r['stage']} | {r['status']} | {r['detail']} |\n" for r in rows)
  +"\nPASS A/B é apenas reprodutibilidade Creality oficial, NÃO homologação Filuna.\n",encoding="utf-8")
 return 1 if any(r["status"]=="FAIL" for r in rows) else 0

if __name__=="__main__":raise SystemExit(main())
