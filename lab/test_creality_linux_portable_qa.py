#!/usr/bin/env python3
"""Creality OEM official A/B byte-level normalization regression tests."""
from pathlib import Path
import tempfile
import unittest

from creality_linux_portable_qa import diff_proof

HEAD=[b"; generated by Creality_Print V7.3.1.6378 on 2026-11-06 at 23:00:00",
      b"; creality_uuid: 11111111-2222-3333-4444-555555555555",
      b"; creality_uuid: 22222222-2222-3333-4444-555555555555"]
def code(uuid=HEAD[1],timestamp=HEAD[0],line_end=b"\n",extrusion=b"G1 X2 E0.1",uuid_at=7):
 arr=[b"; machine",timestamp,b"; profile",b"; info",b"; info",b"; info",uuid,extrusion]
 if uuid_at!=7:
  arr[uuid_at-1],arr[6]=arr[6],arr[uuid_at-1]
 return line_end.join(arr)+line_end

class CrealityByteLevelProofTests(unittest.TestCase):
 def check(self,a,b):
  with tempfile.TemporaryDirectory() as tmp:
   root=Path(tmp);first=root/"A.gcode";second=root/"B.gcode"
   first.write_bytes(a);second.write_bytes(b)
   return diff_proof(first,second,root)

 def test_identical_unchanged(self):
  self.assertEqual(self.check(code(),code())[0],"PASS")

 def test_official_uuid_only_is_accepted(self):
  self.assertEqual(self.check(code(),code(uuid=HEAD[2]))[0],"PASS")

 def test_toolpath_change_is_not_normalized(self):
  self.assertEqual(self.check(code(),code(uuid=HEAD[2],extrusion=b"G1 X2 E0.2"))[0],"FAIL")

 def test_line_ending_change_is_not_normalized(self):
  self.assertEqual(self.check(code(),code(line_end=b"\r\n"))[0],"FAIL")

 def test_uuid_only_allowed_on_line_7(self):
  self.assertEqual(self.check(code(),code(uuid=HEAD[2],uuid_at=6))[0],"FAIL")

 def test_timestamp_only_allowed_on_line_2(self):
  other=b"; generated by Creality_Print V7.3.1.6378 on 2026-11-06 at 23:00:01"
  self.assertEqual(self.check(code(),code(timestamp=other))[0],"PASS")

if __name__=="__main__":unittest.main()
