#!/usr/bin/env python3
"""Snapmaker v2.4.1 U1 vendor CLI reproducibility across DISTINCT seconds.

Runs official SHA-pinned portable with temporary machine-derived nozzle guard.
Hashes raw G-code and normalizes ONLY an observed, exact-generation-timestamp
line located within HEADER_BLOCK. No other G-code differences are tolerated.
This proves only guarded official CLI repeatability, NOT original-source
CLI unmodified / Filuna native parity / LAN/device / supervised physical QA.
"""
from __future__ import annotations
import argparse
import hashlib
import json
from pathlib import Path
import re
import time

from portable_first_qa import OFFICIAL, digest, obtain, extract_executable
from snapmaker_u1_inherit import build_effective_original_presets
from snapmaker_u1_guard_probe import run_cli
from snapmaker_runtime_nozzle_guard_qa import guarded_runtime_process

ROOT=Path(__file__).resolve().parents[1]
DATE_LINE=re.compile(
    rb"^; generated by Snapmaker Orca 2\.4\.1 on (\d{4}-\d{2}-\d{2}) at "
    rb"(\d{2}:\d{2}:\d{2})\r?\n?$"
)


def header_date_only_normalization(gcode:bytes)->dict:
    lines=gcode.splitlines(keepends=True)
    try:
        start=next(i for i,x in enumerate(lines) if x.rstrip(b"\r\n")==b"; HEADER_BLOCK_START")
        end=next(i for i,x in enumerate(lines) if x.rstrip(b"\r\n")==b"; HEADER_BLOCK_END")
    except StopIteration as exc:
        raise ValueError("GCODE_HEADER_BLOCK_REQUIRED") from exc
    if start!=0 or end>100 or end<=start:
        raise ValueError("INVALID_HEADER_BOUNDARIES")
    matching=[(i,x,DATE_LINE.fullmatch(x)) for i,x in enumerate(lines[start+1:end],start+1)
              if DATE_LINE.fullmatch(x)]
    if len(matching)!=1:
        raise ValueError("EXACTLY_ONE_OFFICIAL_TIMESTAMP_LINE_REQUIRED got="+str(len(matching)))
    i,raw,match=matching[0]
    other=b"".join(x for j,x in enumerate(lines) if j!=i)
    return {"line_number":i+1,"timestamp":match.group(1).decode("ascii")+"T"+
            match.group(2).decode("ascii"),
            "original_line":raw.decode("utf-8","replace").rstrip("\r\n"),
            "raw_sha256":hashlib.sha256(gcode).hexdigest(),
            "normalized_sha256":hashlib.sha256(other).hexdigest(),
            "normalized_length_bytes":len(other),
            "original_length_bytes":len(gcode),
            "lines":len(lines)}


def compare_temporally_separated(a:bytes,b:bytes)->dict:
    pa=header_date_only_normalization(a)
    pb=header_date_only_normalization(b)
    if pa["timestamp"]==pb["timestamp"]:
        raise ValueError("SAME_SECOND_NOT_A_VALID_TEMPORAL_AB")
    if pa["normalized_sha256"]!=pb["normalized_sha256"]:
        raise ValueError("NON_TIMESTAMP_GCODE_DIFFERENCE")
    if pa["normalized_length_bytes"]!=pb["normalized_length_bytes"]:
        raise ValueError("NORMALIZED_LENGTH_MISMATCH")
    return {"status":"PASS_HEADER_ONLY_NORMALIZATION",
            "raw_equal":pa["raw_sha256"]==pb["raw_sha256"],
            "normalization_authorized_by_verified_AB":True,
            "allowed": "exact official timestamp line in HEADER_BLOCK only",
            "A":pa,"B":pb,
            "all_other_bytes_equal":True,
            "no_other_lines_excluded":True}


def main():
    parser=argparse.ArgumentParser()
    parser.add_argument("--cache",type=Path,default=Path(".oem-portable-cache"))
    parser.add_argument("--out",type=Path,default=Path("qa-snapmaker-u1-temporal-ab"))
    args=parser.parse_args()
    cache=args.cache.resolve();out=args.out.resolve()
    cache.mkdir(parents=True,exist_ok=True);out.mkdir(parents=True,exist_ok=True)
    rows=[]
    def add(stage,status,details,evidence=""):
        assert status in ("PASS","FAIL","PENDING")
        rows.append({"gate":stage,"status":status,
                     "details":details,"evidence":evidence})
        print("U1_TEMPORAL",stage,status,details,flush=True)
    try:
        cfg=OFFICIAL["snapmaker"]
        archive,url=obtain(cfg,cache)
        exe=extract_executable(archive,cfg["exe"],
                               cache/"snapmaker-portable-extracted").resolve()
        add("OFFICIAL_ZIP","PASS",digest(archive),url)
        effective=build_effective_original_presets(out)
        runtime=out/"runtime-process-copy.json"
        lock=guarded_runtime_process(effective["machine"],effective["process"],runtime)
        (out/"normalization-source.lock.json").write_text(json.dumps(lock,indent=2)+"\n")
        add("VENDOR_ORIGINAL_IMMUTABLE","PASS",
            "machine-derived nozzle, original source/process unchanged",
            "normalization-source.lock.json")
        cube=(ROOT/"fixtures/cube20.stl").resolve()
        gcodes=[]
        for letter in ("A","B"):
            if letter=="B":
                # Exact local timestamp is in header; prove repeatability over
                # DIFFERENT seconds (not merely two files from one second).
                time.sleep(2.5)
            r=run_cli(exe,effective["machine"],runtime,effective["filament"],
                      cube,out,"temporal-"+letter)
            if r["exit_code"]!=0 or len(r["gcodes"])!=1:
                add("CLI_"+letter,"FAIL",
                    "exit="+str(r["exit_code"])+" gcode_count="+str(len(r["gcodes"])),
                    r["log"])
                break
            path=out/r["gcodes"][0]["path"]
            gcodes.append(path)
            add("CLI_"+letter,"PASS",
                "bytes="+str(path.stat().st_size)+" sha="+digest(path),
                str(path.relative_to(out)))
        if len(gcodes)==2:
            outcome=compare_temporally_separated(gcodes[0].read_bytes(),gcodes[1].read_bytes())
            (out/"temporal-ab-proof.json").write_text(json.dumps(
                outcome,indent=2,ensure_ascii=False)+"\n")
            add("SPACED_HEADER_ONLY_A_B","PASS",
                "A="+outcome["A"]["timestamp"]+" B="+outcome["B"]["timestamp"]
                +" normalized_sha="+outcome["A"]["normalized_sha256"],
                "temporal-ab-proof.json")
            # Model/firmware-specific commands are OEM-only smoke checks,
            # NOT validation that any printer would accept or execute them.
            script=gcodes[0].read_bytes()
            required=(b"PRINT_START",b"SM_PRINT_CHECK_SWITCH_EXTRUDER",
                      b"BED_MESH_CALIBRATE",b"PRINT_END")
            missing=[s.decode("ascii") for s in required if s not in script]
            if missing:
                add("U1_OFFICIAL_GCODE_MACROS","FAIL","Missing: "+repr(missing))
            else:
                add("U1_OFFICIAL_GCODE_MACROS","PASS",
                    "required macro names present; not device firmware execution")
        else:
            add("SPACED_HEADER_ONLY_A_B","PENDING","no two successful G-codes")
        add("ORIGINAL_UNMODIFIED_AB","PENDING","original CLI process triggers null access")
        add("FILUNA_NATIVE_PARITY","PENDING","no Filuna native motor comparison")
        add("U1_DEVICE_PROTOCOL","PENDING","network/access/safety ACK not executed")
        add("PHYSICAL_BETA","PENDING","only after internal QA/final build")
    except Exception as exc:
        add("RUNNER","FAIL",type(exc).__name__+": "+str(exc))
    (out/"results.json").write_text(json.dumps(rows,indent=2)+"\n")
    (out/"RESUMO.md").write_text(
        "# Snapmaker U1 temporal G-code A/B (original OEM CLI + temporary guard)\n\n"
        "Only timestamp inside HEADER_BLOCK may differ. Does not imply native Filuna parity.\n\n"
        "| Gate | Status | Details |\n|---|---|---|\n"
        +"".join("| "+r["gate"]+" | "+r["status"]+" | "+
                 r["details"].replace("|","/")+" |\n" for r in rows),
        encoding="utf-8")
    return 1 if any(r["status"]=="FAIL" for r in rows) else 0


if __name__=="__main__":
    raise SystemExit(main())
